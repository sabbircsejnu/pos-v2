using RetailPOS.Application.Common.Formatting;
using ClosedXML.Excel;
using RetailPOS.Application.Inventory.StockCounts;

namespace RetailPOS.API.Services;

internal static class StockCountExcelExporter
{
    public static (byte[] Content, string FileName) Export(StockCountDetailReadModel stockCount, string dateFormat = "yyyy-MM-dd")
    {
        using var workbook = new XLWorkbook();
        var worksheet = workbook.Worksheets.Add("Stock Count");

        worksheet.Cell(1, 1).Value = "Stock Count No";
        worksheet.Cell(1, 2).Value = stockCount.StockCountNo;
        worksheet.Cell(2, 1).Value = "Location";
        worksheet.Cell(2, 2).Value = stockCount.LocationName;
        worksheet.Cell(3, 1).Value = "Stock Count Date";
        worksheet.Cell(3, 2).Value = stockCount.StockCountDate;
        worksheet.Cell(3, 2).Style.DateFormat.Format = UiDateFormatting.Normalize(dateFormat).ToLowerInvariant();
        worksheet.Cell(4, 1).Value = "Generated By";
        worksheet.Cell(4, 2).Value = stockCount.CreatedByName;
        worksheet.Cell(5, 1).Value = "Generated Time";
        worksheet.Cell(5, 2).Value = stockCount.CreatedAt;
        worksheet.Cell(5, 2).Style.DateFormat.Format = UiDateFormatting.Normalize(dateFormat).ToLowerInvariant() + " hh:mm";

        const int headerRow = 7;
        worksheet.Cell(headerRow, 1).Value = "SL";
        worksheet.Cell(headerRow, 2).Value = "Product Name";
        worksheet.Cell(headerRow, 3).Value = "Product Code";
        worksheet.Cell(headerRow, 4).Value = "Variant";
        worksheet.Cell(headerRow, 5).Value = "Current Stock";
        worksheet.Cell(headerRow, 6).Value = "Physical Count";
        worksheet.Cell(headerRow, 7).Value = "Difference";
        worksheet.Cell(headerRow, 8).Value = "Remarks";
        worksheet.Row(headerRow).Style.Font.Bold = true;

        for (var index = 0; index < stockCount.Lines.Count; index++)
        {
            var row = headerRow + index + 1;
            var line = stockCount.Lines[index];
            worksheet.Cell(row, 1).Value = index + 1;
            worksheet.Cell(row, 2).Value = line.ProductName;
            worksheet.Cell(row, 3).Value = line.ProductCode;
            worksheet.Cell(row, 4).Value = line.VariantName;
            worksheet.Cell(row, 5).Value = line.CurrentStock;
            worksheet.Cell(row, 6).Value = line.PhysicalStock;
            worksheet.Cell(row, 7).Value = line.Difference;
            worksheet.Cell(row, 8).Value = line.Remarks;
        }

        worksheet.Columns().AdjustToContents();

        using var stream = new MemoryStream();
        workbook.SaveAs(stream);
        return (stream.ToArray(), $"StockCount_{stockCount.StockCountNo}.xlsx");
    }
}
