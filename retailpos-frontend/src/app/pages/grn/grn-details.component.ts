import { CompanyDateService } from '../../services/company-date.service';
import { getPurchaseLocationName, getPurchaseLocationTypeLabel } from '../../models/purchase-order.model';
import { Component, OnInit, signal, inject  } from '@angular/core';
import { CommonModule, Location } from '@angular/common';
import { ActivatedRoute, Router } from '@angular/router';
import { RouterLink } from '@angular/router';
import { GrnService } from '../../services/grn.service';
import { AlertService } from '../../services/alert.service';
import { ErrorHandlerService } from '../../services/error-handler.service';
import { DocumentPdfService } from '../../services/document-pdf.service';
import { Grn, GrnItem } from '../../models/grn.model';
import { formatUnitQuantity } from '../../services/uom.service';

@Component({
  selector: 'app-grn-details',
  standalone: true,
  imports: [CommonModule, RouterLink],
  templateUrl: './grn-details.component.html',
  styleUrls: ['./grn-details.component.css']
})
export class GrnDetailsComponent implements OnInit {
  private readonly companyDates = inject(CompanyDateService);
  readonly locationTypeLabel = getPurchaseLocationTypeLabel;
  readonly locationName = getPurchaseLocationName;
  grn = signal<Grn | null>(null);
  isLoading = signal(false);
  isCompleting = signal(false);
  isPdfDownloading = signal(false);

  constructor(
    private grnService: GrnService,
    private router: Router,
    private location: Location,
    private route: ActivatedRoute,
    private alertService: AlertService,
    private errorHandler: ErrorHandlerService,
    private documentPdfService: DocumentPdfService
  ) {}

  ngOnInit(): void {
    const id = this.route.snapshot.paramMap.get('id');
    if (id) {
      this.loadGrn(+id);
    }
  }

  loadGrn(id: number): void {
    this.isLoading.set(true);
    this.grnService.getById(id).subscribe({
      next: (response) => {
        this.grn.set(response.data || null);
        this.isLoading.set(false);
      },
      error: (err) => {
        this.alertService.error(this.errorHandler.extractErrorMessage(err));
        this.isLoading.set(false);
        this.location.back();
      }
    });
  }

  completeGrn(): void {
    const grn = this.grn();
    if (!grn) return;
    this.alertService.confirm('Complete this GRN and update stock levels?', () => {
      this.isCompleting.set(true);
      this.grnService.complete(grn.id).subscribe({
        next: () => {
          this.alertService.success('GRN completed and stock updated successfully');
          this.loadGrn(grn.id);
          this.isCompleting.set(false);
        },
        error: (err) => {
          this.alertService.error(this.errorHandler.extractErrorMessage(err));
          this.isCompleting.set(false);
        }
      });
    });
  }

  getPoReference(grn: Grn): string {
    return grn.poOrderNumber || grn.poNumber || `PO-${grn.poId.toString().padStart(6, '0')}`;
  }

  getVariantDetails(item: { variantName?: string; variantAttributes?: string }): string {
    const parts = [item.variantName, item.variantAttributes]
      .map(v => (v ?? '').trim())
      .filter(v => this.hasReadableText(v))
      .filter(v => v.length > 0);

    return parts.join(' - ');
  }

  private hasReadableText(value: string): boolean {
    const trimmed = value.trim();
    if (!trimmed) return false;
    if (trimmed === '{}' || trimmed === '[]' || trimmed.toLowerCase() === 'null') return false;
    if ((trimmed.startsWith('{') && trimmed.endsWith('}')) || (trimmed.startsWith('[') && trimmed.endsWith(']'))) return false;
    return true;
  }

  getCreatedByLabel(grn: Grn): string {
    const createdByName = (grn.creatorName ?? '').trim();
    const notes = (grn as any).notes as string | undefined;
    const isAutoGenerated = typeof notes === 'string' && notes.includes('AUTO_GENERATED_FROM_PURCHASE_ORDER');

    if (isAutoGenerated && createdByName) {
      return `System (Triggered by ${createdByName})`;
    }

    if (createdByName) {
      return createdByName;
    }

    return isAutoGenerated ? 'System' : '-';
  }

  backToList(): void {
    this.location.back();
  }

  getStatusBadgeClass(status: string): string {
    switch (status?.toLowerCase()) {
      case 'full': return 'bg-green-100 text-green-800';
      case 'partial': return 'bg-yellow-100 text-yellow-800';
      default: return 'bg-gray-100 text-gray-800';
    }
  }

  /** Whether the lines carry damaged, rejected or unit details. A plain pcs GRN keeps its original table. */
  showDamageColumns(): boolean {
    return (this.grn()?.items ?? []).some(item => Number(item.damagedQty ?? 0) > 0 || Number(item.rejectedQty ?? 0) > 0);
  }

  quantityText(quantity: number | null | undefined, item: GrnItem): string {
    return item.uomBaseUnitCode ? formatUnitQuantity(quantity, item.uomBaseUnitCode) : String(quantity ?? 0);
  }

  /** How the accepted quantity was physically received. Empty when the item does not track it. */
  packBreakdown(item: GrnItem): string {
    if (item.acceptedSealedPacks === null || item.acceptedSealedPacks === undefined) return '';
    return `${item.acceptedSealedPacks} sealed + ${formatUnitQuantity(item.acceptedLooseQty, item.uomBaseUnitCode)} loose`;
  }

  getVarianceClass(variance: number): string {
    if (variance === 0) return 'text-gray-600';
    return variance > 0 ? 'text-green-600 font-semibold' : 'text-red-600 font-semibold';
  }

  downloadPdf(): void {
    const current = this.grn();
    if (!current) {
      return;
    }

    this.isPdfDownloading.set(true);
    this.documentPdfService.downloadDocument('grn', current.id).subscribe({
      next: (response) => {
        this.documentPdfService.triggerBrowserDownload(response, `GRN-${current.id.toString().padStart(6, '0')}.pdf`);
        this.isPdfDownloading.set(false);
      },
      error: (err) => {
        this.isPdfDownloading.set(false);
        this.alertService.error(this.errorHandler.extractErrorMessage(err));
      }
    });
  }

  formatDateTime(date: string): string {
    if (!date) return '-';
    return this.companyDates.format(date, true, this.companyDates.timeZone());
  }
}
